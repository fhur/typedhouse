import { expect, it } from 'vitest';
import { col, from, table, unionAll, crossJoin, val, relNode, flatOutput, Query, type Rel } from '@chql/core';
import { emitNaive } from '../src/index.js';
const meta = { engine: 'Memory', sortingKey: [], partitionKey: [] };
const source = from(table('t', { id: col.UInt32, s: col.String }, meta));
const first = source.map(r => ({ id: r.id, s: r.s }));
const reversed = source.map(r => ({ s: r.s, id: r.id }));
it('validates every nested branch and rejects captured sibling-union scopes', () => {
  const left = unionAll(source, source);
  const right = unionAll(source, source);
  expect(() => emitNaive(unionAll(left, right.where(() => left.row.id.eq(1))).ir)).toThrow('unbound_column at root.inputs[1].pred.args[0]');
  const malformed = { ...source.ir, kind: 'Limit', input: source.ir, n: -1 } as Rel;
  const nested = relNode({ kind: 'Union', inputs: [source.ir, malformed], all: true, output: source.ir.output });
  expect(() => emitNaive(relNode({ kind: 'Union', inputs: [source.ir, source.ir, nested], all: true, output: source.ir.output }))).toThrow('invalid_limit at root.inputs[2].inputs[1]');
  const cyclic = { kind: 'Union' as const, id: source.ir.id, inputs: [] as Rel[], all: true, output: source.ir.output };
  cyclic.inputs.push(source.ir, cyclic);
  expect(() => emitNaive(cyclic)).toThrow('cyclic_ir at root.inputs[1]');
  const nullable = from(table('nullable', { id: col.Nullable(col.UInt32), s: col.String }, meta));
  expect(() => emitNaive(relNode({ kind: 'Union', inputs: [source.ir, nullable.ir], all: true, output: source.ir.output }))).toThrow('union_descriptor_mismatch at root.inputs[1].output');
});
it('aligns by path, retains identity and freezes wrappers, without scan/order stages', () => {
  const union = unionAll(first, reversed, first);
  expect(Object.isFrozen(union)).toBe(true);
  expect(Object.isFrozen(union.row)).toBe(true);
  expect('thenBy' in union).toBe(false);
  expect('final' in union).toBe(false);
  if (union.ir.kind !== 'Union') throw new Error('Union expected');
  expect(union.ir.inputs[0]).toBe(first.ir);
  expect(union.ir.inputs[2]).toBe(first.ir);
  const before = JSON.stringify(union.ir);
  const plan = emitNaive(union.ir);
  for (const branch of plan.sql.split(' UNION ALL ')) expect(branch).toMatch(/^SELECT `__chql_input`.`id` AS `id`, `__chql_input`.`s` AS `s` FROM/);
  expect(plan.sql.match(/UNION ALL/g)).toHaveLength(2);
  expect(JSON.stringify(union.ir)).toBe(before);
  expect(union.row.id.ir.type).toEqual(col.UInt32.type);
  const live = from(table('live', { id: col.UInt32, s: col.String }, { ...meta, source: { kind: 'test' } }));
  expect(unionAll(live, live).caps.live).toBe(true);
  expect(unionAll(live, source).caps.live).toBe(false);
});
it('keeps branch boundaries and Param identity in first SQL appearance order', () => {
  const shared = val('same', col.String);
  const branch = source.map(r => ({ id: r.id, s: shared })).orderBy(r => r.id.desc()).limit(1).distinct();
  const other = source.map(r => ({ s: val('same', col.String), id: r.id }));
  const plan = emitNaive(unionAll(branch, other, branch).where(r => r.s.eq('outside')).ir);
  expect(plan.params).toEqual({ p0: 'same', p1: 'same', p2: 'outside' });
  expect(plan.sql.match(/\{p0:String\}/g)).toHaveLength(2);
  expect(plan.sql.match(/LIMIT 1/g)).toHaveLength(2);
  expect(plan.sql.match(/SELECT DISTINCT/g)).toHaveLength(2);
  expect(plan.sql).toMatch(/UNION ALL.*\) AS `__chql_input` WHERE/);
});
it('retains nested and expanded hostile paths despite reversed side order', () => {
  const arr = from(table('a', { ['a.b']: col.Array(col.UInt64) }, meta));
  const a = crossJoin({ ['__proto__']: arr, '42': arr }).leftArrayJoin(r => r.__proto__['a.b'], '__chql_leaf_0');
  const b = crossJoin({ '42': arr, ['__proto__']: arr }).leftArrayJoin(r => r.__proto__['a.b'], '__chql_leaf_0');
  const plan = emitNaive(unionAll(a, b).ir);
  expect(Object.values(plan.columnPaths!)).toEqual([['42', 'a.b'], ['__proto__', 'a.b'], ['__chql_leaf_0']]);
  expect(unionAll(a, b).row.__proto__['a.b'].ir.type).toEqual(col.Array(col.UInt64).type);
});
it('rejects descriptor coercion and forged branch/output/scope/mode/arity with node paths', () => {
  const wider = from(table('float', { id: col.Float64, s: col.String }, meta));
  expect(() => unionAll(source, wider)).toThrow('union_descriptor_mismatch at Union.inputs[1].output: ["id"]');
  const raw = (inputs: readonly Rel[], all = true, output = source.ir.output) => relNode({ kind: 'Union', inputs, all, output });
  expect(() => emitNaive(raw([source.ir]))).toThrow('union_input_count at root.inputs');
  expect(() => emitNaive(raw([source.ir, source.ir], 'ALL' as unknown as boolean))).toThrow('invalid_union_mode at root.all');
  expect(() => emitNaive(raw([source.ir, wider.ir]))).toThrow('union_descriptor_mismatch at root.inputs[1].output');
  expect(() => emitNaive(raw([source.ir, source.map(r => r.id).ir]))).toThrow('union_schema_mismatch at root.inputs[1].output');
  expect(() => emitNaive(raw([source.ir, source.ir], true, flatOutput([['id', col.String.type]])))).toThrow('invalid_output at root');
  const foreign = from(table('foreign', { id: col.UInt32, s: col.String }, meta));
  expect(() => emitNaive(raw([source.ir, source.where(() => foreign.row.id.eq(1)).ir]))).toThrow('unbound_column at root.inputs[1].pred.args[0]');
  expect(() => emitNaive(unionAll(source, source).where(() => source.row.id.eq(1)).ir)).toThrow('unbound_column at root.pred.args[0]');
  expect(emitNaive(raw([source.ir, source.ir], false)).sql).toContain(' UNION DISTINCT ');
  expect(() => (unionAll as unknown as (...args: unknown[]) => unknown)(source)).toThrow('union_input_count');
  expect(() => (unionAll as unknown as (...args: unknown[]) => unknown)(source, {})).toThrow('invalid_union_input at Union.inputs[1]');
  const missing = new Query(source.map(r => r.id).ir, source.caps);
  expect(() => (unionAll as unknown as (...args: unknown[]) => unknown)(source, missing)).toThrow('union_schema_mismatch');
});
