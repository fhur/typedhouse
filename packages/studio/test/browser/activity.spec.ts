import { expect, test } from '@playwright/test';
import { open, sendMessage, startHarness, uiOf, waitForTurns, type Harness } from './support.js';

let harness: Harness;
test.beforeEach(async ({}, info) => { harness = await startHarness(uiOf(info)); });
test.afterEach(async () => { await harness?.stop(); });

test('latest call and earlier counts are scoped to each user, including pending sends', async ({ page }) => {
  await open(page, harness);
  await sendMessage(page, 'transparent multicall');
  const live = page.getByTestId('generating');
  await expect(live).toContainText('Working…');
  const indicator = live.locator('.activity-spinner');
  await expect(indicator).toBeVisible();
  await expect(indicator).toHaveAttribute('aria-hidden', 'true');
  await expect(indicator).toHaveCSS('animation-name', 'activity-spin');
  const label = live.locator('.activity-label-live');
  await expect(label).toHaveCSS('animation-name', 'activity-glare');
  await expect(live.locator('.activity-log > summary')).toHaveCSS('list-style-type', 'none');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(indicator).toHaveCSS('animation-name', 'none');
  await expect(label).toHaveCSS('animation-name', 'none');
  await expect(label).toHaveCSS('background-image', 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await expect(live.locator('.activity-log > summary')).toContainText('Searching docs…');
  await expect(live.locator('.activity-log > summary')).toContainText('[Details]');
  await expect(live.locator('.activity-log > summary')).toContainText('Writing query…');
  await expect(live.locator('.activity-log > summary')).toContainText('[+1 tool call]');
  for (const tool of await page.locator('.activity-tool').all()) await expect(tool).not.toBeVisible();
  await live.locator('.activity-log > summary').click();
  await expect(live.locator('.activity-tool')).toHaveCount(2);
  for (const tool of await live.locator('.activity-tool').all()) await expect(tool).not.toHaveAttribute('open', '');
  await waitForTurns(page, 2);
  await sendMessage(page, 'hang');
  await expect(live).toHaveCount(1);
  await expect(live.locator('.activity-log > summary')).toContainText('Working…');
  await expect(live.locator('.activity-log > summary')).not.toContainText('Writing query');
  await expect(live.locator('.activity-log > summary')).not.toContainText('+1');
  await live.getByRole('button', { name: /stop/ }).click();
  await expect(live).toHaveCount(0);
  await expect(page.locator('.activity-spinner')).toHaveCount(0);
  // A turn with no activity adds no empty disclosure; editing it keeps earlier logs.
  await expect(page.locator('.activity-log')).toHaveCount(1);
  await page.locator('.turn[data-kind="user"]').last().click();
  await page.getByRole('button', { name: /edit & resend/ }).click();
  await expect(page.locator('.activity-log')).toHaveCount(1);
});

test('public activity arrives during a new send, expands safely, and survives reopening', async ({ page }) => {
  await open(page, harness);
  let settled = false;
  page.on('response', response => { if (response.url().includes('chat.send')) settled = true; });
  await sendMessage(page, 'transparent');
  const text = page.locator('.activity-text').filter({ hasText: 'Checking <b>public progress</b>.' });
  const live = page.getByTestId('generating');
  await expect(live).toContainText('Working…');
  await expect(live.locator(':scope > details > summary')).toContainText('Writing query…');
  await expect(text).not.toBeVisible();
  await expect(page.locator('.activity-log')).not.toHaveAttribute('open', '');
  await live.locator(':scope > details > summary').click();
  await expect(text).toBeVisible();
  expect(settled).toBe(false);
  await expect(page.locator('[data-testid="generating"]')).toBeVisible();
  await expect(page.locator('.turn[data-kind="user"]')).toHaveCount(1);
  await expect(page.locator('.turn-user-pending')).toHaveCount(0);
  const tool = page.locator('details.activity-tool');
  await expect(tool).toHaveCount(1);
  const inputs = tool.getByRole('region', { name: 'Inputs' });
  const result = tool.getByRole('region', { name: 'Result' });
  await expect(tool).not.toHaveAttribute('open', '');
  await tool.locator('summary').focus();
  await page.keyboard.press('Enter');
  await expect(inputs.locator('pre')).toContainText('<img src=x onerror=alert(1)>');
  await expect(tool).toHaveAttribute('data-status', 'error');
  await expect(result.locator('pre')).toContainText('<img src=x onerror=alert(1)>');
  await expect(page.locator('.activity img, .activity b')).toHaveCount(0);
  await page.fill('#composer', 'draft kept while tools run');
  await waitForTurns(page, 2);
  await expect(page.locator('#composer')).toHaveValue('draft kept while tools run');
  await expect(tool).toHaveAttribute('open', '');
  const ids = await page.locator('[data-activity]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-activity')));
  await page.reload();
  await expect(page.locator('.activity-log > summary')).toContainText('1 tool call [Details]');
  await expect(page.locator('.activity-log > summary')).toContainText('error');
  await expect(text).not.toBeVisible();
  await page.locator('.activity-log > summary').click();
  await expect(tool).toHaveCount(1);
  await expect(tool).not.toHaveAttribute('open', '');
  await expect(text).toContainText('Checking <b>public progress</b>.');
  expect(await page.locator('[data-activity]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-activity')))).toEqual(ids);
  await expect(page.locator('.turn[data-turn]')).toHaveCount(2);
  // Activity is not a selectable editor version, and rewriting its user hides it.
  await page.locator('.turn[data-kind="user"]').click();
  await page.getByRole('button', { name: /edit & resend/ }).click();
  await expect(page.locator('[data-activity]')).toHaveCount(0);
});
