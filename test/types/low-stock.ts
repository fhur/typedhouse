import { expectTypeOf } from 'expect-type';
import { col, exp, from, sum, table, uniq, type Infer, type Query, type IsLive, type Expr } from '@chql/core';
import { latest, lowStockCategories, cIndices, type ComponentIndicesRow, type Versioned } from '../../packages/compiler/test/fixtures/corpus/low-stock.js';
const result = lowStockCategories('acme');
type Result = { category: string; components: bigint; stockIndex: number; leadTimeIndex: number; priceIndex: number; warned: bigint };
expectTypeOf<Infer<typeof result>>().toEqualTypeOf<Result>();
expectTypeOf<Infer<typeof result>>().not.toBeAny();
const indices = latest(cIndices);
expectTypeOf<Infer<typeof indices>>().toEqualTypeOf<ComponentIndicesRow>();
expectTypeOf<Infer<typeof indices>>().not.toBeAny();
expectTypeOf<IsLive<typeof indices>>().toEqualTypeOf<false>();
const base = { tenantId: col.String, entityId: col.String, version: col.UInt32 };
const meta = { engine: 'MergeTree', sortingKey: [], partitionKey: [] };
const floats = from(table('floats', { ...base, value: col.Float64 }, meta));
const ints = from(table('ints', { ...base, value: col.UInt32 }, meta));
const sf = latest(floats).aggregate(g => ({ value: sum(g.value) }));
const si = latest(ints).aggregate(g => ({ value: sum(g.value) }));
expectTypeOf<Infer<typeof sf>>().toEqualTypeOf<{ value: number }>();
expectTypeOf<Infer<typeof si>>().toEqualTypeOf<{ value: bigint }>();
expectTypeOf<Infer<typeof sf>>().not.toBeAny();
expectTypeOf<Infer<typeof si>>().not.toBeAny();
const erased: Query<Versioned & { value: number }> = floats;
const se = latest(erased).aggregate(g => ({ value: sum(g.value) }));
expectTypeOf<Infer<typeof se>>().toEqualTypeOf<{ value: number | bigint }>();
expectTypeOf<Infer<typeof se>>().not.toBeAny();
const live = latest(from(table('live', base, { ...meta, source: { kind: 'test' } })));
expectTypeOf<IsLive<typeof live>>().toEqualTypeOf<true>();
const nullable = from(table('nullable', { n: col.Nullable(col.Float64), s: col.Nullable(col.String) }, meta));
const unary = nullable.map(r => ({ n: exp(r.n), method: r.n.exp() }));
const aggregate = nullable.aggregate(g => ({ n: exp(sum(g.n)), s: uniq(g.s) }));
expectTypeOf<Infer<typeof unary>>().toEqualTypeOf<{ n: number | null; method: number | null }>();
expectTypeOf<Infer<typeof aggregate>>().toEqualTypeOf<{ n: number | null; s: bigint }>();
expectTypeOf<Infer<typeof unary>>().not.toBeAny();
expectTypeOf<Infer<typeof aggregate>>().not.toBeAny();
expectTypeOf(exp(nullable.row.n).name).toEqualTypeOf<'n'>();
expectTypeOf(exp(nullable.row.n).mode).toEqualTypeOf<'row'>();
// Width-erased expressions remain supported without inventing descriptor evidence.
declare const n: Expr<number>;
expectTypeOf(exp(n).ir.type).toEqualTypeOf<Expr<number>['ir']['type'] & { readonly kind: 'scalar'; readonly name: 'Float64' }>();
