import { expectTypeOf } from 'expect-type';
import { col, columnExpr, countIf, from, sum, table, val, type Expr, type NodeId } from '@chql/core';
import { stockHistory } from '../../packages/compiler/test/fixtures/corpus/stock-history.js';
const id = 1 as NodeId;
const row = columnExpr(col.UInt64, id, ['x'], 'x', 'row');
const grouped = columnExpr(col.Nullable(col.UInt64), id, ['x'], 'x', 'grouped');
const a = row.between(1n, val(3n));
const b = grouped.between(val(1n), grouped);
const c = sum(grouped).between(null, 3n);
expectTypeOf(a).toEqualTypeOf<Expr<boolean, 'x'>>(); expectTypeOf(a).not.toBeAny();
expectTypeOf(b).toEqualTypeOf<Expr<boolean | null, 'x', 'grouped'>>(); expectTypeOf(b).not.toBeAny();
expectTypeOf(c).toEqualTypeOf<Expr<boolean | null, 'x', 'agg'>>(); expectTypeOf(c).not.toBeAny();
const q = from(table('ranges', { n: col.Float64, lo: col.Nullable(col.Float64), hi: col.Float64, at: col.DateTime64(3) }, { engine: 'Memory', sortingKey: [], partitionKey: [] }));
const flags = q.map(r => ({ flag: r.n.between(r.lo, r.hi), at: r.at.between(new Date(0), new Date(1000)) }));
expectTypeOf(flags._rowType).toEqualTypeOf<{ flag: boolean | null; at: boolean }>(); expectTypeOf(flags._rowType).not.toBeAny();
const tally = q.aggregate(g => ({ n: countIf(g.n.between(g.lo, val(5))) }));
expectTypeOf(tally._rowType).toEqualTypeOf<{ n: bigint }>(); expectTypeOf(tally._rowType).not.toBeAny();
const history = stockHistory(new Date(0), new Date(1000));
expectTypeOf(history._rowType).toEqualTypeOf<{ entityId: string; at: Date; version: number; stock: number }>(); expectTypeOf(history._rowType).not.toBeAny();
