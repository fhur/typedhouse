import { mkdtempSync, mkdirSync, symlinkSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
const directory = mkdtempSync(join(tmpdir(), 'chql-query-consumer-'));
function run(command, args, cwd = process.cwd()) {
  const result = spawnSync(command, args, { cwd, encoding: 'utf8', timeout: 120000 });
  if (result.status !== 0) throw new Error(`${command}: ${result.stdout}\n${result.stderr}`);
}
try {
  mkdirSync(join(directory, 'node_modules/@chql'), { recursive: true });
  for (const name of ['core', 'compiler', 'client']) symlinkSync(resolve(`packages/${name}`), join(directory, `node_modules/@chql/${name}`), 'dir');
  for (const name of ['expect-type', '@types']) symlinkSync(resolve(`node_modules/${name}`), join(directory, `node_modules/${name}`), 'dir');
  writeFileSync(join(directory, 'package.json'), '{"type":"module"}');
  writeFileSync(join(directory, 'consumer.ts'), readFileSync('test/types/query.ts', 'utf8') + '\nimport type { AggregationSnapshot } from "./aggregation.d.ts";\nconst snapshotQuery = q.groupBy(r => r.id).aggregate(g => ({ total: sum(g.id), count: count() }));\nexpectTypeOf<Infer<typeof snapshotQuery>>().toEqualTypeOf<AggregationSnapshot>();\nexpectTypeOf<Infer<typeof snapshotQuery>>().not.toBeAny();\n');
  writeFileSync(join(directory, 'expansion.ts'), `import { expectTypeOf } from 'expect-type';
import { from, table, col, join, type Infer } from '@chql/core';
import type { JoinSnapshot } from './join.d.ts';
const side = from(table('t', { id: col.UInt64 }, { engine: 'Memory', sortingKey: [], partitionKey: [] }));
const joined = join({ a: side, b: side }).on(r => r.a.id.eq(r.b.id));
expectTypeOf<Infer<typeof joined>>().toEqualTypeOf<JoinSnapshot>();
expectTypeOf<Infer<typeof joined>>().not.toBeAny();
import type { ArrayJoinSnapshot } from './array-join.d.ts';
const q = from(table('s', { specs: col.Array(col.Tuple({ name: col.Nullable(col.String) })), ids: col.Array(col.UInt64) }, { engine: 'Memory', sortingKey: [], partitionKey: [] })).final().leftArrayJoin(r => r.specs, 'pair');
expectTypeOf<Infer<typeof q>>().toEqualTypeOf<ArrayJoinSnapshot>();
expectTypeOf<Infer<typeof q>>().not.toBeAny();
import type { JoinedArrayJoinSnapshot } from './joined-array-join.d.ts';
const nestedExpanded = join({ a: q, b: side }).on(r => r.a.ids.arrayElement(1).eq(r.b.id)).leftArrayJoin(r => r.a.ids, 'item');
expectTypeOf<Infer<typeof nestedExpanded>>().toEqualTypeOf<JoinedArrayJoinSnapshot>();
expectTypeOf<Infer<typeof nestedExpanded>>().not.toBeAny();
`);
  writeFileSync(join(directory, 'joined-array-join.d.ts'), readFileSync('test/types/snapshots/joined-array-join.d.ts', 'utf8'));
  writeFileSync(join(directory, 'join.d.ts'), readFileSync('test/types/snapshots/join.d.ts', 'utf8'));
  writeFileSync(join(directory, 'array-join.d.ts'), readFileSync('test/types/snapshots/array-join.d.ts', 'utf8'));
  writeFileSync(join(directory, 'aggregation.d.ts'), readFileSync('test/types/snapshots/aggregation.d.ts', 'utf8'));
  writeFileSync(join(directory, 'tsconfig.json'), JSON.stringify({ compilerOptions: { target: 'ES2022', module: 'NodeNext', moduleResolution: 'NodeNext', strict: true, exactOptionalPropertyTypes: true, noEmit: true, types: ['node'] }, include: ['consumer.ts', 'expansion.ts'] }));
  writeFileSync(join(directory, 'smoke.mjs'), `
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { toTypeScript, count, sum, col, table, from, registerCompiler, join } from '@chql/core';
import { emitNaive } from '@chql/compiler';
import { createClient, decoder, rowDecoder } from '@chql/client';
const q = from(table('t', { id: col.UInt64 }, { engine: 'Memory', sortingKey: [], partitionKey: [] })).where(r => r.id.eq(2n)).map(r => ({ id: r.id })).limit(10);
assert.throws(() => q.toSQL(), /compiler_not_registered/);
registerCompiler(emitNaive);
assert.deepEqual({...q.toSQL().params}, {p0: '2'});
assert.equal(decoder(col.UInt64.type)('2'), 2n);
const structural = from(table('s', { specs: col.Array(col.Tuple({ name: col.Nullable(col.String) })), ids: col.Array(col.UInt64) }, { engine: 'Memory', sortingKey: [], partitionKey: [] }))
  .where(r => r.ids.hasAny([2n])).map(r => ({ names: r.specs.element('name'), first: r.specs.arrayElement(-1).element('name'), size: r.ids.length(), empty: r.ids.empty() }));
assert.deepEqual({...structural.toSQL().params}, { p0: 'name', p1: '-1', p2: 'name', p3: '[2]' });
assert.deepEqual(decoder(structural.toSQL().columns.names)(['a', null]), ['a', null]);
assert.equal(decoder(structural.toSQL().columns.empty)(0), false);
const ordered = structural.map(r => r.first).distinct().orderBy(r => r.first.desc().nullsLast()).thenBy(r => r.first).limit(2);
assert.match(ordered.toSQL().sql, /SELECT DISTINCT/);
assert.match(ordered.toSQL().sql, /DESC NULLS LAST/);
assert.equal('thenBy' in ordered, false);
const rollup = q.groupBy(r => r.id).aggregate(g => ({ total: sum(g.id), count: count() }));
assert.match(rollup.toSQL().sql, /GROUP BY/);
const mapped = Object.entries(rollup.toSQL().columns).map(([k, t]) => JSON.stringify(k) + ': ' + toTypeScript(t)).join('; ');
assert.equal(readFileSync('aggregation.d.ts', 'utf8'), 'export type AggregationSnapshot = { ' + mapped + ' };\\n');
assert.equal(decoder(rollup.toSQL().columns.total)('4'), 4n);
assert.equal('map' in q.groupBy(r => r.id), false);
const expanded = from(table('s', { specs: col.Array(col.Tuple({ name: col.Nullable(col.String) })), ids: col.Array(col.UInt64) }, { engine: 'Memory', sortingKey: [], partitionKey: [] })).final().leftArrayJoin(r => r.specs, 'pair');
assert.match(expanded.toSQL().sql, /FINAL/);
assert.match(expanded.toSQL().sql, /LEFT ARRAY JOIN/);
assert.equal('final' in expanded, false);
const expansionType = Object.entries(expanded.toSQL().columns).map(([k, t]) => JSON.stringify(k) + ': ' + toTypeScript(t)).join('; ');
assert.equal(readFileSync('array-join.d.ts', 'utf8'), 'export type ArrayJoinSnapshot = { ' + expansionType + ' };\\n');
const joined = join({ a: q, b: q }).on(r => r.a.id.eq(r.b.id));
assert.match(joined.toSQL().sql, /INNER ALL JOIN/);
const schemaType = schema => '{ ' + (schema.shape === 'flat' ? schema.order.map(k => JSON.stringify(k) + ': ' + toTypeScript(schema.columns[k])) : [...schema.inputs.map(([alias, child]) => JSON.stringify(alias) + ': ' + schemaType(child)), ...(schema.fields ? schema.fields.order.map(k => JSON.stringify(k) + ': ' + toTypeScript(schema.fields.columns[k])) : [])]).join('; ') + ' }';
assert.equal(readFileSync('join.d.ts', 'utf8'), 'export type JoinSnapshot = ' + schemaType(joined.ir.output) + ';\\n');
const nestedExpanded = join({ a: expanded, b: q }).on(r => r.a.ids.arrayElement(1).eq(r.b.id)).leftArrayJoin(r => r.a.ids, 'item');
assert.equal(readFileSync('joined-array-join.d.ts', 'utf8'), 'export type JoinedArrayJoinSnapshot = ' + schemaType(nestedExpanded.ir.output) + ';\\n');
const expandedPlan = nestedExpanded.toSQL();
assert.deepEqual(Object.values(expandedPlan.columnPaths), [['a', 'specs'], ['a', 'ids'], ['a', 'pair'], ['b', 'id'], ['item']]);
assert.equal(toTypeScript(expandedPlan.columns[Object.keys(expandedPlan.columns).at(-1)]), 'bigint');
const plan = joined.toSQL();
assert.deepEqual(rowDecoder(plan.columns, plan.columnPaths)(Object.fromEntries(Object.keys(plan.columns).map(k => [k, '2']))), { a: { id: 2n }, b: { id: 2n } });
await createClient().close();
`);
  run(process.execPath, ['smoke.mjs'], directory);
  const version = process.env.CHQL_TYPESCRIPT_VERSION;
  run('pnpm', [...(version ? ['--package', `typescript@${version}`, 'dlx', 'tsc'] : ['exec', 'tsc']), '--project', join(directory, 'tsconfig.json')]);
  console.log('Built Query/compiler/client ESM and exact/not-any consumer types passed.');
} finally { rmSync(directory, { recursive: true, force: true }); }
